  window.renderMarkdown = async function (markdown, printMode = false) {
    state.generation += 1;
    const generation = state.generation;
    window.markdownRenderCount = (window.markdownRenderCount || 0) + 1;
    state.printMode = printMode === true;
    state.lastMarkdown = String(markdown ?? "");
    document.documentElement.classList.toggle("print-mode", state.printMode);
    closeImageViewer();

    configureMarked();

    const separated = splitFrontmatter(state.lastMarkdown);
    let body = separated?.body ?? state.lastMarkdown;
    let frontmatter = null;
    if (separated && CAPABILITIES.frontmatter && window.__mdviewerReadFrontmatter) {
      const parsed = await window.__mdviewerReadFrontmatter(
        separated.source,
        separated.body
      );
      if (generation !== state.generation) return { cancelled: true };
      body = parsed.body;
      frontmatter = parsed.card;
    } else if (separated) {
      frontmatter = buildRawFrontmatter(separated.source);
    }

    const fragment = sanitizeMarkdownHTML(marked.parse(body));

    const outline = decorateHeadings(fragment);
    decorateAlerts(fragment);
    decorateTaskLists(fragment);
    decorateFootnotes(fragment);
    const codeBlocks = decorateCodeBlocks(fragment);
    decorateImages(fragment);

    const content = document.getElementById("content");
    content.replaceChildren();
    if (frontmatter) content.appendChild(frontmatter);
    content.appendChild(fragment);

    state.outline = outline;

    if (CAPABILITIES.prism) {
      highlightWithPrism(codeBlocks);
    } else if (CAPABILITIES.highlightJS && window.__mdviewerHighlightBlocks) {
      // Asynchronous and generation-guarded: a stale highlight never lands.
      window.__mdviewerHighlightBlocks(codeBlocks, generation);
    }

    if (CAPABILITIES.mermaid && window.__mdviewerRenderDiagrams) {
      window.__mdviewerRenderDiagrams(
        codeBlocks.filter((block) => block.language === "mermaid"),
        generation,
        state.printMode
      );
    }

    return {
      resources: Array.from(content.querySelectorAll("img[src]")).map((image) =>
        image.getAttribute("src")
      ),
      outline,
      height: document.body.scrollHeight,
      generation,
    };
  };

