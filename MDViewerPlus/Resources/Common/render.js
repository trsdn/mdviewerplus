  function isSearchableTextNode(node, root) {
    if (!node || !node.data || node.data.length === 0) return false;

    let element = node.parentElement;
    while (element) {
      if (
        element.matches(
          "script,style,noscript,summary,button,input,textarea,select,option," +
            "[role='button'],[role='searchbox'],[contenteditable='true']"
        ) ||
        element.hidden ||
        element.getAttribute("aria-hidden") === "true"
      ) {
        return false;
      }

      const style = getComputedStyle(element);
      if (
        style.display === "none" ||
        style.visibility === "hidden" ||
        style.visibility === "collapse" ||
        Number.parseFloat(style.opacity) === 0
      ) {
        return false;
      }
      if (element === root) break;
      element = element.parentElement;
    }
    if (element !== root) return false;

    const range = document.createRange();
    range.selectNodeContents(node);
    return range.getClientRects().length > 0;
  }

  function searchFlowContainer(node, root) {
    let element = node.parentElement;
    while (element && element !== root) {
      const display = getComputedStyle(element).display;
      if (display !== "inline" && display !== "contents") return element;
      element = element.parentElement;
    }
    return root;
  }

  window.mdviewerCountMatches = function (query) {
    const needle = String(query ?? "").toLowerCase();
    const root = document.getElementById("content");
    if (!root || needle.length === 0) return 0;

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        return isSearchableTextNode(node, root)
          ? NodeFilter.FILTER_ACCEPT
          : NodeFilter.FILTER_REJECT;
      },
    });
    const chunks = [];
    let previousContainer = null;
    while (walker.nextNode()) {
      const node = walker.currentNode;
      const container = searchFlowContainer(node, root);
      if (previousContainer && previousContainer !== container) chunks.push("\n");
      chunks.push(node.data);
      previousContainer = container;
    }

    const text = chunks.join("").toLowerCase();
    let count = 0;
    let offset = 0;
    while (offset <= text.length - needle.length) {
      const match = text.indexOf(needle, offset);
      if (match < 0) break;
      count += 1;
      offset = match + needle.length;
    }
    return count;
  };

  window.mdviewerScrollToSlug = function (slug) {
    const target = document.getElementById(String(slug));
    if (!target) return false;
    target.scrollIntoView({ block: "start" });
    target.setAttribute("tabindex", "-1");
    target.focus({ preventScroll: true });
    return true;
  };

  /**
   * Forces every lazy renderer to finish and waits for stable layout so print
   * output never captures a half-rendered page.
   */
  window.waitForResources = async function (timeoutMilliseconds = 8000) {
    const deadline = Date.now() + timeoutMilliseconds;

    if (window.__mdviewerPreparePrint) {
      await window.__mdviewerPreparePrint(state.generation, deadline);
    }

    const images = Array.from(document.images);
    await Promise.all(
      images.map((image) => {
        if (image.complete) return Promise.resolve();
        return new Promise((resolve) => {
          const finish = () => resolve();
          image.addEventListener("load", finish, { once: true });
          image.addEventListener("error", finish, { once: true });
          window.setTimeout(finish, Math.max(0, deadline - Date.now()));
        });
      })
    );

    await new Promise((resolve) => {
      let completed = false;
      const finish = () => {
        if (completed) return;
        completed = true;
        resolve();
      };
      // Offscreen print WKWebViews can throttle animation frames entirely.
      // The timer guarantees progress while the double frame still provides
      // stable layout for visible previews.
      window.setTimeout(finish, 60);
      requestAnimationFrame(() => requestAnimationFrame(finish));
    });
    return true;
  };

