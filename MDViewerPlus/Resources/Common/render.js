  window.applyTheme = function (theme) {
    if (!theme || (theme.category !== "light" && theme.category !== "dark")) {
      return false;
    }

    for (const token of Object.keys(themeProperties)) {
      const value = theme[token];
      if (typeof value !== "string" || !trustedColorPattern.test(value)) {
        return false;
      }
    }
    for (const [token, property] of Object.entries(themeProperties)) {
      document.documentElement.style.setProperty(property, theme[token]);
    }
    document.documentElement.style.colorScheme = theme.category;
    state.themeCategory = theme.category;
    if (window.__mdviewerFullThemeChanged) {
      window.__mdviewerFullThemeChanged(theme.category, state.generation);
    }
    return true;
  };

