  const generatedIdPattern = /^(?:footnote-|footnote-ref-|user-content-)[A-Za-z0-9_-]{1,128}$/;
  const generatedClassPattern = /^(?:footnote|footnotes|footnote-ref|footnote-backref|data-footnotes|sr-only)$/;
  const fragmentPattern = /^#[^\s<>"']{1,512}$/;

